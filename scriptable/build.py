"""Builds the single-file Scriptable app from the shared web UI.

    python scriptable/build.py   ->   scriptable/Line Monitor.js

The dashboard's HTML, CSS and JavaScript come from app/static, so the NAS
version and the iPhone-only version always look the same.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "scriptable" / "src"
STATIC = ROOT / "app" / "static"

html = (STATIC / "index.html").read_text()
body = re.search(r"<body>(.*)</body>", html, re.S).group(1)
body = re.sub(r"<script[^>]*></script>", "", body).strip()

out = (SRC / "main.js").read_text()
out = out.replace("/*__CRYPTO__*/", (SRC / "crypto.js").read_text().strip())
out = out.replace('/*__CSS__*/""', json.dumps((STATIC / "style.css").read_text()))
out = out.replace('/*__APPJS__*/""', json.dumps((STATIC / "app.js").read_text()))
out = out.replace('/*__BODY__*/""', json.dumps(body))

header = ("// Variables used by Scriptable.\n"
          "// These must be at the very top of the file. Do not edit.\n"
          "// icon-color: deep-blue; icon-glyph: signal;\n"
          "// Generated by scriptable/build.py from scriptable/src and app/static. Edit those, not this file.\n")
target = ROOT / "scriptable" / "Line Monitor.js"
target.write_text(header + out)
print(f"wrote {target.relative_to(ROOT)} ({len(header + out):,} bytes)")
